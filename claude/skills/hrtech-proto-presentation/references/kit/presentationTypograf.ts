const SHORT_WORDS_RE =
    /(^|[\s\u00a0«(—])(в|во|на|с|со|к|ко|у|о|об|от|до|за|из|по|и|а|но|не|ни|да|то|же|бы|ли|под|над|без|при|про|для|или|как|что|где|уже|ещё|всё|все|это|их|её|его|им|три|два|обе|мой|мои) /giu;

/*
 * Русская экранная типографика: неразрывные пробелы после предлогов и союзов,
 * перед длинным тире, после чисел и знаков, без одиноких коротких слов в конце строки.
 */
export function typograf(text: string): string {
    let out = text
        .replace(/Я Team/g, 'Я\u00a0Team')
        .replace(/ — /g, '\u00a0— ')
        .replace(/№(\d)/g, '№\u00a0$1')
        .replace(/(\d(?:[,.]\d+)?%?) (?=[А-Яа-яЁёA-Za-z«])/g, '$1\u00a0')
        .replace(/([≥≤±~]) /g, '$1\u00a0');

    out = out.replace(SHORT_WORDS_RE, '$1$2\u00a0');
    out = out.replace(SHORT_WORDS_RE, '$1$2\u00a0');
    out = out.replace(/ ([А-Яа-яЁёA-Za-z«»]{1,7}[.?!»]?)$/, '\u00a0$1');
    return out;
}
