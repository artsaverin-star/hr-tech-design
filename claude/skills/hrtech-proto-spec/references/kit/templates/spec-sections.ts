/** Дорожка: ряд узлов слева направо. */
export interface MapLaneDef {
    /** Заголовок над первым экраном: событие или исход, 1–4 слова. Обязателен — иначе «Дорожка N». */
    title: string;
    /** Одна строка «Когда …»: «Когда прав не хватает самому сотруднику». */
    note?: string;
    /** Узел, из которого дорожка растёт. Нет — основной путь или отдельная история. */
    from?: string;
    /** Разбор: взаимоисключающие случаи, между ними стрелок нет. Только для 2+ узлов. */
    cases?: boolean;
    nodes: string[];
}

export interface MapSectionDef {
    /** Название сценария БЕЗ номера. */
    title: string;
    /** Путь секции словами: «Старт → черновик → ответ». */
    subtitle: string;
    lanes: MapLaneDef[];
}

