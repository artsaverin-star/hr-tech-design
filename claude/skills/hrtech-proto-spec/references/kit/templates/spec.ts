/**
 * СПЕК-МАНИФЕСТ ПРОТОТИПА — заготовка из комплекта hrtech-proto-spec (v6).
 *
 * Имена полей — КОНТРАКТ (SKILL.md §1): их читают «Карта», генератор снимков и
 * перенос в Figma. Не переименовывай поля и не добавляй синонимы.
 *
 * Пиши кадры ПОСЛЕ рецептов (шаг 7): у каждого кадра с кликами уже есть проверенный рецепт.
 *
 * Как заполнять (по одному кадру на каждое состояние, которое видит человек):
 *  - кадр — это другой ВИД интерфейса (открылось окно, сменился экран, пришёл ответ, ошибка),
 *    а не другое количество отмеченного: «отмечен один пункт» и «отмечено три» — один кадр;
 *  - `id` — короткий смысловой код строчными: 'home', 'draft', 'result', 'error-rate';
 *  - `title` — СОБЫТИЕ или РЕЗУЛЬТАТ, 2–4 слова, из заголовка экрана в выводе `--probe`:
 *        так: «Настройки открыты», «Токен не подошёл», «Подписка подключена», «Вход через Яндекс ID»
 *        не так: «Открыл настройки» (действие зрителя), «Шторка токена» (имя компонента),
 *                 «Подключить Claude» (текст кнопки), «Яндекс ID: экран 2» (номер);
 *    слов, которых нет на экране (название тикета, обещание из описания, «пусто»), в подписях не
 *    бывает — spec-lint сверяет со снимком (L21);
 *  - `caption` — ОДНА фраза до 160 знаков: что видно на снимке по сравнению с прошлым шагом.
 *    В «кавычках» — только дословный текст со снимка (не текст демо-панели). Без «видишь», без
 *    CSS, размеров, параметров адреса и слов «рецепт»/«seed»;
 *  - `zone` — название секции карты (ровно как `title` секции в `spec-sections.ts`, без номера);
 *  - `url` — адрес, который открывает ИМЕННО это состояние: `'?seed=<id>'` (рецепт в
 *    spec-seeds.ts стартует с главной) или `'?<параметр, который читает прототип>&seed=<id>'`;
 *  - `next` — переходы: `label` ДОСЛОВНО как текст кнопки из вывода `--probe` (по нему ищется
 *    кнопка на снимке); «Далее», «Закрыть», «Готово» не придумывать. Шаги одной цепочки
 *    связывай ВСЕГДА: рецепт кадра B = рецепт A + клик «X» → у A `next: [{ label: 'X', to: 'B' }]`.
 *    `kind: 'system'` — переход делает система (ответ пришёл, сбой, таймер), без label.
 *    Кнопки демо-панели прототипа (⚙ в разведке) в label НЕ пишутся;
 *  - телефон: каждый кадр заворачивай в `...withPhone({ … })` — он добавит `<id>@m` с тем же
 *    адресом. Разведка на 375 пишет «страница шире экрана» — телефонной вёрстки нет: кадры БЕЗ
 *    withPhone и в spec-sections.ts `MAP_NO_MOBILE = { '*': 'Прототип только десктопный (1440)' }`.
 *
 * Ромб (`SPEC_DECISIONS`) — один вопрос и ветки-ЗНАЧЕНИЯ ответа, не «Да/Нет»:
 *    система решает → событие строчными + kind: 'system' («токен не подошёл», «сервис перегружен»);
 *    человек решает → дословная кнопка («Разрешить», «Отмена»).
 *
 * Проверка: `node src/scripts/spec-lint.mjs --stage frames` → «Кадры чистые.»
 */

/** Переход из кадра: строкой (= `{ to }`) или объектом. */
export type SpecTransition =
    | string
    | { to: string; kind?: 'user' | 'system'; label?: string; anchor?: string };

/** Светофор: ставь, только если различает (не «wip» на каждом кадре). */
export type SpecStatus = 'ready' | 'wip' | 'question';

export interface SpecFrame {
    id: string;
    title: string;
    caption?: string;
    zone: string;
    platform: 'desktop' | 'mobile';
    url: string;
    figmaNodeId?: string;
    status?: SpecStatus;
    next?: SpecTransition[];
}

/** Ромб-развилка: вопрос и ветки-значения ответа. `kind: 'system'` — исход выбирает система. */
export interface SpecDecision {
    id: string;
    question: string;
    branches: { label?: string; to: string; tone?: 'yes' | 'no'; kind?: 'user' | 'system' }[];
}

/** Помощник: кадр десктопа и его телефон одной строкой. */
const withPhone = (frame: Omit<SpecFrame, 'platform'>): SpecFrame[] => [
    { ...frame, platform: 'desktop' },
    { ...frame, id: `${frame.id}@m`, next: undefined, platform: 'mobile' },
];

