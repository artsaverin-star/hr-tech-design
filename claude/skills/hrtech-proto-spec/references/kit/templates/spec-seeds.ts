/**
 * РЕЦЕПТЫ ШАГОВ СПЕКИ (`?seed=<id>`) — заготовка из комплекта hrtech-proto-spec (v6).
 * Движок — `spec-seed-runtime.ts` (копируется как есть). Пиши рецепты ДО кадров (шаг 6 регламента).
 *
 * Рецепт нужен, когда состояние нельзя открыть адресом, а только действиями человека. Ключ
 * рецепта = `id` кадра. Рецепт проигрывает путь С ЧИСТОГО СТАРТА по адресу кадра.
 *
 * АДРЕС КАДРА = стартовый адрес + `seed`:
 *   - прототип не читает параметров адреса (обычный случай) → `url: '?seed=<id>'`, и рецепт
 *     начинается с кликов входа в раздел: `{ text: 'Меню' }, { text: 'Настройки' }, …`;
 *   - прототип читает параметр (ищи `searchParams.get(` / `URLSearchParams` в его src) →
 *     `url: '?<этот параметр>=…&seed=<id>'`, и рецепт начинается с того экрана.
 *
 * ПОДКЛЮЧЕНИЕ:
 *   Б (по умолчанию) — ничего не делать: `<SpecGate>` в src/index.tsx сам запускает рецепт после
 *     первой отрисовки. Рецепты — только `clicks`.
 *   А (у прототипа модель с редьюсером и хочется `actions`) — в файле модели:
 *         import { applySpecSeed, hasSpecSeed } from './spec-seeds';
 *         const initial = hasSpecSeed() ? applySpecSeed(createInitial(), reducer) : createInitial();
 *     при `hasSpecSeed()` не читать и не писать localStorage. SpecGate тогда рецепт не трогает.
 *
 * ТЕКСТЫ В `clicks` — ТОЛЬКО из вывода разведки, не по памяти и не «как обычно называют».
 * Лучше всего пройти путь в разведке и перенести «Готовый рецепт» ОДИН В ОДИН:
 *     node src/scripts/spec-snapshots.mjs --base <адрес> --probe '?' --click 'Меню' --click 'Настройки'
 * Хватает начала строки: «Claude» найдёт «Claude Подключить» (в кавычках разведки — ровно то,
 * что переносится; «…» после кавычек не переносить). Поле — по подписи, placeholder или
 * aria-label: `{ text: 'Почта', type: 'a@b.c' }`; список `<select>` — вариантом по его тексту:
 * `{ text: 'Город', type: 'Москва' }`. Прокрутка: `{ scroll: 'bottom' }`, `{ scroll: 600 }`,
 * `{ scroll: 'bottom', text: 'Цена за ночь' }` (область, где лежит этот текст) — отличие ниже
 * первого экрана ВСЕГДА докручивай в рецепте, иначе на снимке его не будет.
 * Фокус после клика рецепт снимает сам (тултипа на снимке не будет); `keepFocus: true` — оставить;
 * окно открылось с автофокусом на кнопке с тултипом и тултип всё равно на снимке — `blur: true`.
 * Кнопки демо-панели прототипа (⚙ в выводе разведки: «Пустая выдача», «Ищем долго») — тоже
 * клики рецепта: так открываются состояния, которые дизайнер вынес на панель.
 * Шторкам и ответам — `wait: 800…1500`.
 *
 * Проверка КАЖДОГО рецепта сразу после записи — на обеих ширинах должно быть «рецепт: ready»,
 * без строк «!», а на снимке — нужный экран:
 *     node src/scripts/spec-snapshots.mjs --base <адрес> --probe '<url кадра>'
 */

import { createSeedApplier, hasSeed, type SeedRecipe } from './spec-seed-runtime';

/* Вариант А: подставь тип состояния и действия своей модели вместо unknown. */
type State = unknown;
type Action = unknown;

export const SEED_RECIPES: Record<string, SeedRecipe<State, Action>> = {
    /* Состояние открывается адресом без кликов — пустой рецепт. */
    home: {},
    /* TODO: пример — клик по кнопке с экрана `home` и ожидание шторки. */
    'next-step': { clicks: [{ blur: true, text: 'Текст кнопки дословно', wait: 900 }] },
};

/** Ключи рецептов — по ним `spec-lint.mjs` сверяет `?seed=` кадров. */
export const SEED_IDS = Object.keys(SEED_RECIPES);

export const hasSpecSeed = hasSeed;

/** Второй аргумент — что сделать со стартом перед рецептом (вариант А: например, пропустить знакомство). */
export const applySpecSeed = createSeedApplier<State, Action>(SEED_RECIPES, state => state);
